#!/usr/bin/env bash
# T1 device benchmarks (run from the workstation). Batch 1, 3 runs (fresh processes) per config.
#   Orin #1 : TensorRT 8.5 FP16, synchronous per-inference timing (src/bench/trt_sync_bench.py).
#             Every model is built TWICE: BUILD=default and BUILD=nocublas
#             (--tacticSources=-CUBLAS,-CUBLAS_LT); both are timed.
#             No clock locking (DVFS, as deployed); warm-up >= 2 s and >= 50 iterations; GPU
#             cur_freq read at the end of the warm-up and sampled during timing; tegrastats
#             (100 ms) logged during each run. nvpmodel / clocks / thermal archived
#             before + after every run. Builds and timed runs hold
#             flock /tmp/dn_orin_bench.lock on the Orin (shared with other benchmark jobs).
#   RPi 4B  : onnxruntime FP32, 3 threads pinned with taskset to cores 0,2,3 (core 1 is used by
#             a background service, garbage.service, which is left running). Warm-up >= 2 s and
#             >= 50 iterations. Runs interleaved across models; top / vcgencmd / garbage.service
#             core archived before + after each run.
# Raw JSON lines and logs are copied back to results/T1/raw/<dir>/; results.csv is
# generated by src/t1/make_results.py.
# Usage: run_bench.sh {orin|rpi|both} model1.onnx [model2.onnx ...]   (paths under results/T1/models)
# Env:   NRUNS (3), BUILDS ("default nocublas"), ORIN_RAW (orin1_v07), RPI_RAW (rpi4b_v07),
#        ORIN_WD (trt_v07: engine work dir on the Orin)
set -euo pipefail
ROOT=${DEB_ROOT:-$(cd "$(dirname "$0")/../.." && pwd)}
M=$ROOT/results/T1/models
RAW=$ROOT/results/T1/raw
NRUNS=${NRUNS:-3}
BUILDS=${BUILDS:-"default nocublas"}
ORIN_RAW=${ORIN_RAW:-orin1_v07}
RPI_RAW=${RPI_RAW:-rpi4b_v07}
ORIN_WD=${ORIN_WD:-trt_v07}
J=${ORIN_HOST:-orin}
R=${RPI_HOST:-rpi}
RD='~/dendritic-edge-bench/T1'
WHERE=$1; shift
MODELS=("$@")

orin() {
  mkdir -p "$RAW/$ORIN_RAW"
  ssh $J "mkdir -p $RD/bin $RD/models $RD/$ORIN_WD"
  scp -q $ROOT/src/bench/trt_sync_bench.py $ROOT/src/bench/run_trt_sync_jetson.sh $J:$RD/bin/
  for m in "${MODELS[@]}"; do
    scp -q "$M/$m" $J:$RD/models/
    lab=$(basename "$m" .onnx)
    for b in $BUILDS; do
      ssh $J "cd $RD && bash bin/run_trt_sync_jetson.sh \$PWD/models/$m fp16 \$PWD/$ORIN_WD $lab $NRUNS $b" \
        | tee -a "$RAW/$ORIN_RAW/stdout.jsonl" || echo "ORIN FAILED: $m $b" | tee -a "$RAW/$ORIN_RAW/failures.txt"
    done
    rsync -a --exclude '*.engine' $J:dendritic-edge-bench/T1/$ORIN_WD/ "$RAW/$ORIN_RAW/"
  done
}

rpi_env() {  # $1 = tag
  ssh $R "echo '## $1' \$(date -Iseconds); P=\$(systemctl show -p MainPID --value garbage.service); \
    echo garbage.service pid=\$P active=\$(systemctl is-active garbage.service) psr=\$(ps -o psr= -p \$P) pcpu=\$(ps -o pcpu= -p \$P); \
    vcgencmd measure_temp; vcgencmd measure_clock arm; vcgencmd get_throttled; \
    cat /sys/devices/system/cpu/cpu0/cpufreq/scaling_governor; cat /proc/loadavg; top -b -n1 | head -15"
}

rpi() {
  mkdir -p "$RAW/$RPI_RAW"
  ssh $R "mkdir -p $RD/models $RD/out_v07"
  scp -q $ROOT/src/bench/bench_ort.py $R:$RD/
  for m in "${MODELS[@]}"; do scp -q "$M/$m" $R:$RD/models/; done
  for r in $(seq 1 "$NRUNS"); do
    for m in "${MODELS[@]}"; do
      lab=$(basename "$m" .onnx)
      rpi_env "before $lab run $r" >> "$RAW/$RPI_RAW/env_log.txt"
      ssh $R "cd $RD && taskset -c 0,2,3 ~/venvs/dendritic/bin/python bench_ort.py models/$m --threads 3 \
        --device rpi4b-8gb --label $lab --run $r --out out_v07/results.jsonl" \
        | tee -a "$RAW/$RPI_RAW/stdout.jsonl" || echo "RPI FAILED: $m run $r" | tee -a "$RAW/$RPI_RAW/failures.txt"
      rpi_env "after $lab run $r" >> "$RAW/$RPI_RAW/env_log.txt"
    done
  done
  scp -q $R:$RD/out_v07/results.jsonl "$RAW/$RPI_RAW/results.jsonl"
}

case $WHERE in
  orin) orin ;;
  rpi) rpi ;;
  both) orin & rpi; wait ;;
esac
