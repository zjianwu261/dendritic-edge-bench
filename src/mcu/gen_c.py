"""T1m step 3: emit model.h (weights as const __code tables) for src/mcu/c/infer.c.

dANN-LRF: sparse index tables, not a dense mask:
  w1[n*SYN+t]  int8   synapse weights of dendrite n (synapses sorted by pixel index)
  off1[n*SYN+t] uint8 pixel offset relative to base1[n] (all 16 synapses of a local RF lie
                     within a few image rows, so the offset fits one byte; asserted)
  base1[n]     uint16 first pixel of the RF
  b1[n]        int16/int32 dendrite bias
  w2[n]        int8   weight dendrite n -> its soma (soma j owns dendrites j*D .. j*D+D-1)
  b2[j], w3, b3      soma bias, dense output layer
MLP: dense row-major w1 (H1x784), w2 (H2xH1), w3 (10xH2).
dANN-PRNG (step 5): no off1/base1; the synapse positions of dendrite n are regenerated on chip by
  rf_gen (src/mcu/c/prng_rf.c, spec in prng_rf.py) and w1[n*SYN+t] is stored in generator order.
model.h puts all #defines before the tables; with MODEL_DEFINES_ONLY only the defines are seen.
"""
import numpy as np

from prng_rf import rf_c, rf_indices


def _arr(ctype, name, a, per_line=24):
    a = np.asarray(a).ravel()
    body = []
    for i in range(0, len(a), per_line):
        body.append("  " + ",".join(str(int(v)) for v in a[i:i + per_line]) + ",")
    return f"static const CODE {ctype} {name}[{len(a)}] = {{\n" + "\n".join(body) + "\n};\n"


def _bias_type(b):
    return "int16_t" if (b.min() >= -32768 and b.max() <= 32767) else "int32_t"


def dann_tables(q, M1, d, s, syn):
    n_d = d * s
    W1q = q["W1q"]  # (n_d, 784)
    base = np.zeros(n_d, np.int64)
    off = np.zeros((n_d, syn), np.int64)
    w1 = np.zeros((n_d, syn), np.int64)
    for n in range(n_d):
        idx = np.sort(np.nonzero(M1[:, n])[0])
        assert len(idx) == syn
        base[n] = idx[0]
        off[n] = idx - idx[0]
        w1[n] = W1q[n, idx]
    assert off.max() <= 255, off.max()
    # every nonzero weight is covered by the index table
    assert np.abs(W1q).sum() == np.abs(w1).sum()
    w2 = np.array([q["W2q"][n // d, n] for n in range(n_d)])
    return dict(base1=base, off1=off, w1=w1, w2=w2)


def prng_tables(q, M1, d, s, syn, model_seed):
    n_d = d * s
    W1q = q["W1q"]
    idx, _ = rf_indices(n_d, model_seed)
    assert idx.shape == (n_d, syn)
    # the regenerated positions are exactly the training mask
    chk = np.zeros_like(M1)
    chk[idx.T, np.arange(n_d)[None, :]] = 1
    assert (chk == M1).all()
    w1 = np.take_along_axis(W1q, idx, axis=1)
    assert np.abs(W1q).sum() == np.abs(w1).sum()
    w2 = np.array([q["W2q"][n // d, n] for n in range(n_d)])
    return dict(w1=w1, w2=w2)


def emit(q, kind, cfg, path, name, syn=16, M1=None, mask_source="official", model_seed=None):
    lines = [f"/* generated by src/mcu/gen_c.py: {name} */", "#ifndef T1M_MODEL_H", "#define T1M_MODEL_H",
             '#include "platform.h"', f'#define MODEL_NAME "{name}"',
             f"#define SH1 {q['sh1']}", f"#define SH2 {q['sh2']}"]
    b1t, b2t, b3t = _bias_type(q["b1q"]), "int32_t", "int32_t"
    b2t = _bias_type(q["b2q"])
    b3t = _bias_type(q["b3q"])
    arrays = []
    if kind == "dann" and mask_source == "prng":
        d, s = cfg["d"], cfg["s"]
        t = prng_tables(q, M1, d, s, syn, model_seed)
        lines += ["#define MODEL_DANN_PRNG 1", f"#define RF_C 0x{rf_c(model_seed):04x}u", f"#define D {d}",
                  f"#define SYN {syn}", f"#define H1 {d * s}", f"#define H2 {s}"]
        arrays.append(_arr("int8_t", "w1", t["w1"]))
        arrays.append(_arr(b1t, "b1", q["b1q"]))
        arrays.append(_arr("int8_t", "w2", t["w2"]))
        tables = dict(w1=t["w1"].size)
    elif kind == "dann":
        d, s = cfg["d"], cfg["s"]
        t = dann_tables(q, M1, d, s, syn)
        lines += ["#define MODEL_DANN 1", f"#define D {d}", f"#define SYN {syn}",
                  f"#define H1 {d * s}", f"#define H2 {s}"]
        arrays.append(_arr("int8_t", "w1", t["w1"]))
        arrays.append(_arr("uint8_t", "off1", t["off1"]))
        arrays.append(_arr("uint16_t", "base1", t["base1"]))
        arrays.append(_arr(b1t, "b1", q["b1q"]))
        arrays.append(_arr("int8_t", "w2", t["w2"]))
        tables = dict(w1=t["w1"].size, off1=t["off1"].size, base1=2 * t["base1"].size)
    else:
        h1, h2 = q["W1q"].shape[0], q["W2q"].shape[0]
        lines += ["#define MODEL_MLP 1", f"#define H1 {h1}", f"#define H2 {h2}"]
        arrays.append(_arr("int8_t", "w1", q["W1q"]))
        arrays.append(_arr(b1t, "b1", q["b1q"]))
        arrays.append(_arr("int8_t", "w2", q["W2q"]))
        tables = dict(w1=q["W1q"].size, w2=q["W2q"].size)
    if kind == "dann":
        tables["w2"] = t["w2"].size
    lines.append("#ifndef MODEL_DEFINES_ONLY")
    lines += arrays
    lines.append(_arr(b2t, "b2", q["b2q"]))
    lines.append(_arr("int8_t", "w3", q["W3q"]))
    lines.append(_arr(b3t, "b3", q["b3q"]))
    lines.append("#endif /* MODEL_DEFINES_ONLY */")
    lines.append("#endif")
    sz = lambda t_, n: n * (2 if t_ == "int16_t" else 4)
    tables.update(b1=sz(b1t, len(q["b1q"])), b2=sz(b2t, len(q["b2q"])), w3=q["W3q"].size,
                  b3=sz(b3t, len(q["b3q"])))
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    tables["total"] = int(sum(tables.values()))
    return {k: int(v) for k, v in tables.items()}
